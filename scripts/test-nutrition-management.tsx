import assert from "node:assert/strict";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";

import { NutritionManagement } from "../src/components/nutrition-management";
import { ManualNutritionBuilder } from "../src/components/manual-nutrition-builder";

const activeVersion = { id: "one", active: true, versionNumber: 1, calories: 2000, proteinGrams: 100, carbsGrams: 200, fatsGrams: 60, mealCount: 3, goal: "Mantenimiento", reason: "Plan inicial", createdAt: "2026-01-01", restrictions: [] };
const home = renderToStaticMarkup(<NutritionManagement planName="Mi dieta" activeVersion={activeVersion} versions={[activeVersion]} />);
assert.match(home, /Dieta activa/);
assert.match(home, /Crear dieta manual/);
assert.match(home, /href="\/nutrition\/builder\/manual"/);
assert.match(home, /Historial de dietas/);
assert.match(home, /href="\/dashboard\?tab=nutrition"/);
assert.match(home, /lucide-layout-dashboard/);
assert.doesNotMatch(home, /Tus versiones|2000 kcal|Ver detalles/);
const active = renderToStaticMarkup(<NutritionManagement planName="Mi dieta" activeVersion={activeVersion} versions={[activeVersion]} initialSection="active" />);
assert.match(active, /Volver a gestionar dietas/);
assert.match(active, /Volver al dashboard/);
assert.match(active, /Configurar dieta activa/);
const empty = renderToStaticMarkup(<NutritionManagement planName={null} activeVersion={null} versions={[]} />);
assert.match(empty, /Todavía no tienes una dieta activa/);
const newEditor = renderToStaticMarkup(<ManualNutritionBuilder foods={[]} />);
assert.match(newEditor, /href="\/nutrition\/builder"/);
assert.match(newEditor, /href="\/dashboard\?tab=nutrition"/);
const editEditor = renderToStaticMarkup(<ManualNutritionBuilder foods={[]} initialDiet={{ versionId: "one", name: "Mi dieta", meals: [] }} />);
assert.match(editEditor, /href="\/nutrition\/builder\?section=active"/);
assert.match(editEditor, /Volver a mi dieta activa/);
assert.match(editEditor, /lucide-layout-dashboard/);
const meals = ["Desayuno", "Comida", "Cena"].map((name) => ({ name, suggestedTime: null, items: [] }));
const accordion = renderToStaticMarkup(<ManualNutritionBuilder foods={[]} initialDiet={{ versionId: "one", name: "Mi dieta", meals }} />);
assert.equal((accordion.match(/aria-expanded="true" aria-controls="meal-editor-/g) ?? []).length, 1);
assert.equal((accordion.match(/aria-expanded="false" aria-controls="meal-editor-/g) ?? []).length, 2);
assert.match(accordion, /Desayuno/);
assert.match(accordion, /Comida/);
assert.match(accordion, /Cena/);
const totals = renderToStaticMarkup(<ManualNutritionBuilder foods={[{ id: "food", name: "Ejemplo", category: "protein", calories: 100, protein: 20, carbs: 10, fats: 5 }]} initialDiet={{ versionId: "one", name: "Mi dieta", meals: [{ name: "Comida", suggestedTime: null, items: [{ foodId: "food", role: "protein", quantityGrams: 150 }] }] }} />);
assert.match(totals, /aria-label="Resumen nutricional de la dieta"/);
assert.match(totals, /<dt[^>]*>Calorías<\/dt><dd[^>]*>150 <span[^>]*>kcal<\/span><\/dd>/);
assert.match(totals, /<dt[^>]*>Proteína<\/dt><dd[^>]*>30 <span[^>]*>g<\/span><\/dd>/);
assert.match(totals, /<dt[^>]*>Hidratos<\/dt><dd[^>]*>15 <span[^>]*>g<\/span><\/dd>/);
assert.match(totals, /<dt[^>]*>Grasas<\/dt><dd[^>]*>8 <span[^>]*>g<\/span><\/dd>/);
console.log("Gestor y editor de dietas: secciones y navegación correctas.");
